#!/usr/bin/env python3
"""Copy the simulation core into the Unreal project as the OwlightSim module's sources.

    python unreal/sync_sim.py <path-to-UnrealProjects/Owlight>

Copies sim/include and sim/src (not tools/tests), and generates EmbeddedData.cpp from data/*.json
exactly as the CMake build does, so the shipped catalog is embedded. Run after any change to sim/
or data/, before building the Unreal project. The copy is not committed; the repo is the source.
"""
import pathlib, shutil, sys

repo = pathlib.Path(__file__).resolve().parent.parent
proj = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else None
if not proj or not (proj / "Owlight.uproject").exists():
    sys.exit("usage: sync_sim.py <UnrealProjects/Owlight>  (no Owlight.uproject found)")

dst = proj / "Source" / "OwlightSim" / "sim"
if dst.exists():
    shutil.rmtree(dst)
shutil.copytree(repo / "sim" / "include", dst / "include")
(dst / "src").mkdir(parents=True)
for f in (repo / "sim" / "src").iterdir():
    if f.suffix in (".cpp", ".h"):
        shutil.copy2(f, dst / "src" / f.name)

tpl = (repo / "sim" / "src" / "EmbeddedData.cpp.in").read_text(encoding="utf-8")
for name in ("foods", "habitats", "jobs", "types"):
    tpl = tpl.replace(f"@OWLIGHT_{name.upper()}_JSON@", (repo / "data" / f"{name}.json").read_text(encoding="utf-8"))
tpl = tpl.replace("GENERATED by CMake", "GENERATED by unreal/sync_sim.py")
(dst / "src" / "EmbeddedData.cpp").write_text(tpl, encoding="utf-8")
print(f"synced sim -> {dst}")
